export const FEATURE_MAP = Object.fromEntries(FEATURES.map((f) => [f.slug, f])) as Record<string, Feature>;

export function featuresIn(category: CategoryKey) {
  return FEATURES.filter((f) => f.category === category);
}

/** Features in the same category first, then others, excluding the given one. */
export function relatedFeatures(slug: string, count = 3) {
  const self = FEATURE_MAP[slug];
  if (!self) return [];
  const same = FEATURES.filter((f) => f.slug !== slug && f.category === self.category);
  const rest = FEATURES.filter((f) => f.slug !== slug && f.category !== self.category);
  return [...same, ...rest].slice(0, count);
}
