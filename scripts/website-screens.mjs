/**
 * Copies the product screenshots (docs/demo/shots, produced by docs/tools/shoot.cjs)
 * into the marketing website as WebP, and writes their sizes and marker notes to
 * src/website/content/screens.generated.ts.
 *
 * Re-run after refreshing the screenshots:  npm run website:screens
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const shots = path.join(root, 'docs/demo/shots');
const outDir = path.join(root, 'public/website/screens');
const manifest = path.join(root, 'src/website/content/screens.generated.ts');

fs.mkdirSync(outDir, { recursive: true });

const entries = [];
for (const file of fs.readdirSync(shots).filter((f) => f.endsWith('.png')).sort()) {
  const id = file.replace(/\.png$/, '');
  const meta = fs.existsSync(path.join(shots, `${id}.json`)) ? JSON.parse(fs.readFileSync(path.join(shots, `${id}.json`), 'utf8')) : {};
  const img = sharp(path.join(shots, file));
  const { width, height } = await img.metadata();
  await img.webp({ quality: 82, effort: 5 }).toFile(path.join(outDir, `${id}.webp`));
  entries.push({ id, width, height, mobile: width < 900, notes: (meta.markers ?? []).map((m) => m.note).filter(Boolean) });
}

const body = entries
  .map((e) => `  '${e.id}': { src: '/website/screens/${e.id}.webp', width: ${e.width}, height: ${e.height}, mobile: ${e.mobile}, notes: ${JSON.stringify(e.notes)} },`)
  .join('\n');

fs.writeFileSync(
  manifest,
  `// Generated by scripts/website-screens.mjs from docs/demo/shots. Do not edit by hand.\n\nexport const SCREENS = {\n${body}\n} as const;\n\nexport type ScreenId = keyof typeof SCREENS;\n`,
);
console.log(`${entries.length} screenshots → public/website/screens, manifest → ${path.relative(root, manifest)}`);
